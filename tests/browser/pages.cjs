// Run against createFixture() from tests/unit/pages-routes.mjs, with page already on
// its origin. The optional shots directory records desktop, narrow and dark views.
async (page, { shots = '' } = {}) => {
  const prefix = new URL('/_pleiad/s/alpha/', page.url()).href;
  const results = [], errors = [];
  const check = (condition, label) => { if (!condition) throw new Error(label); results.push(label); };
  page.on('pageerror', error => errors.push(error.message));
  const open = async (kind, path, extra = {}) => {
    await page.goto(`${prefix}${kind}?${new URLSearchParams({ ...extra, ...(path ? { path } : {}) })}`);
    await page.locator('#content[aria-busy="false"]').waitFor();
    check(await page.locator('.error').count() === 0, `${kind}: loads without an error`);
  };
  const shot = async name => { if (shots) await page.screenshot({ path:`${shots}/${name}.png`, fullPage:false, scale:'css' }); };
  await page.setViewportSize({ width:1280, height:860 });
  await open('file', 'README.md');
  check(await page.locator('article h1').innerText() === 'ブラウザー統合', 'Markdown uses the existing sanitized renderer');
  check(await page.evaluate(() => !globalThis.untrusted && !document.querySelector('main script')), 'Markdown does not execute file content');
  check(await page.locator('.metadata').count() === 1, 'Fetched time and size occur once above the body');
  check(await page.locator('main > header').count() === 0, 'The page does not duplicate the outer toolbar header');
  await shot('file-1280');
  check(await page.locator('article a').filter({ hasText:'コード' }).getAttribute('href').then(href => new URL(href, page.url()).searchParams.get('path') === 'app.mjs:2'), 'Markdown links keep their line number');
  await page.locator('article a').filter({ hasText:'メモ' }).click();
  await page.locator('article h1').filter({ hasText:'作業メモ' }).waitFor();
  check(true, 'Relative Markdown links retain the file base');
  await open('file', 'README.md');
  await page.evaluate(() => window.dispatchEvent(new CustomEvent('pleiad:page-command', { detail:{ type:'view', view:'source' } })));
  await page.locator('.source-line').first().waitFor();
  check((await page.locator('.source').innerText()).includes('<script>'), 'Source shows literal file content');
  await page.evaluate(() => window.dispatchEvent(new CustomEvent('pleiad:page-command', { detail:{ type:'tree', open:true } })));
  await page.locator('#tree:not([hidden]) .tree-line').first().waitFor();
  check(await page.locator('#tree a').count() > 0, 'Outer toolbar command exposes the existing file tree');
  await open('dir', '.');
  check(await page.locator('.directory .file-name').count() >= 8, 'Folder lists file names and metadata');
  await shot('folder-1280');
  await open('git');
  await page.locator('.cg-row:not(.wt)').first().waitFor();
  check(await page.locator('.gp-tabs [data-t]').count() === 2, 'Git keeps the existing graph and Worktree tabs');
  await page.locator('.fr').first().click();
  await page.locator('.dx').waitFor();
  check((await page.locator('.dx').innerText()).includes('export const ready = true'), 'Git renders parsed hunks through the existing diff renderer');
  await page.locator('[data-da="side"]').click();
  check(await page.locator('.sbs').count() === 1, 'Git supports side by side diffs');
  await shot('git-1280');
  await page.locator('[data-da="back"]').click();
  await shot('git-graph-1280');
  await page.locator('.cg-row:not(.wt)').first().click();
  await page.locator('.cg-row:not(.wt)[aria-expanded="true"]').waitFor();
  const commitFiles = page.locator('.cg-row:not(.wt)').first().locator('..').locator('.ins .fr');
  await commitFiles.first().waitFor();
  check(await commitFiles.count() === 1, 'A commit opens its file list below the graph row');
  await page.locator('[data-t="worktrees"]').click();
  await page.locator('.wrow:not(.sk)').first().click();
  await page.locator('.wdet .fr').waitFor();
  check((await page.locator('.wdet').first().innerText()).includes('app.mjs'), 'Worktree details use the same authenticated page API');
  await page.locator('.wrow:not(.sk)').nth(1).click();
  const keepButton = page.locator('.wt-item-acts').getByRole('button', { name:'残す', exact:true });
  await keepButton.waitFor();
  await page.evaluate(() => {
    globalThis.__requests = [];
    globalThis.plyPage = message => { globalThis.__requests.push(JSON.parse(message)); };
  });
  await keepButton.click();
  check(await keepButton.isDisabled() && await page.locator('.wt-item[data-state=keep]').count() === 0, 'Worktree keep waits for the host completion');
  await page.evaluate(() => window.dispatchEvent(new CustomEvent('pleiad:page-result', { detail:{ requestId:globalThis.__requests.at(-1).requestId, ok:false, error:'cancelled' } })));
  await page.locator('.wt-item [role=alert]').waitFor();
  check(await keepButton.isEnabled() && await page.locator('.wt-item[data-state=keep]').count() === 0, 'A rejected host write cannot display a successful keep');
  check(await page.evaluate(async () => {
    const { requestResult } = await import('/_pleiad/assets/pages/bridge.mjs');
    const result = requestResult('worktree', { action:'keep', id:'notes', kept:true });
    const requestId = globalThis.__requests.at(-1).requestId;
    window.dispatchEvent(new CustomEvent('pleiad:page-result', { detail:{ requestId, ok:true, result:true } }));
    return await result;
  }), 'Host completion replies resolve the matching request');
  await page.locator('.wrow:not(.sk)').nth(1).click();
  await page.setViewportSize({ width:360, height:800 }); await shot('git-360');
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Git fits 360 pixels');
  await page.setViewportSize({ width:1280, height:860 });
  await open('plugins');
  check(await page.locator('.plugin-row').count() === 3, 'Instructions, skills and connections are displayed');
  check(!(await page.locator('main').innerText()).includes('SECRET'), 'Plugin configuration stays out of the page');
  await shot('plugins-1280');
  await open('new');
  check((await page.locator('main h2').allTextContents()).join('|') === 'この会話|可視化|最近のファイル|作業フォルダー', 'New tab has the conversation, visualization, recent and folder sections');
  check(await page.locator('.viz-row').count() === 3, 'Visualizations list as rows separate from shortcuts');
  check(await page.locator('.viz-row .viz-saved').count() === 2, 'Missing and path-less rows carry the saved-version badge');
  await shot('new-1280');
  await page.setViewportSize({ width:360, height:800 });
  await shot('new-360');
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'New tab fits 360 pixels');
  await open('file', 'README.md'); await shot('file-360');
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Markdown fits 360 pixels');
  await open('dir', '.'); await shot('folder-360');
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Folder fits 360 pixels');
  await open('file', 'table.csv');
  check(await page.locator('.data-table tbody tr').count() === 500, 'Table limits the body to 500 rows');
  check(await page.locator('.limit-note').count() === 1, 'Table explains its limit');
  await open('file', 'table.tsv');
  check(await page.locator('.data-table thead th').count() === 2, 'TSV keeps its delimiter');
  await open('file', 'long.txt:5990');
  check(await page.locator('.source-line').count() === 5000 && await page.locator('#line-5990.selected').count() === 1, 'Source limits 5000 lines around the requested line');
  await open('file', 'shape.svg');
  check(await page.locator('img.image-preview').count() === 1 && await page.evaluate(() => !globalThis.untrusted), 'SVG runs as an image');
  await open('file', 'manual.pdf');
  check(await page.locator('canvas.pdf-canvas').count() === 1 && await page.locator('canvas').evaluate(c => c.width > 0), 'PDF is rendered by the existing PDF dependency');
  await open('attachment', 'app.mjs');
  await page.evaluate(() => { globalThis.__requests = []; globalThis.plyPage = message => globalThis.__requests.push(JSON.parse(message)); });
  await page.getByRole('button', { name:'この会話で使う' }).click();
  check(await page.evaluate(() => globalThis.__requests[0]?.type === 'use-file' && globalThis.__requests[0]?.sessionId === 'alpha'), 'Attachment asks the host to use the file');
  await page.route('**/api/env*', route => route.fulfill({ json:{ lang:'en', theme:'dark' } }));
  await page.setViewportSize({ width:1280, height:860 });
  await open('new');
  check(await page.locator('html').getAttribute('lang') === 'en' && await page.locator('html').getAttribute('data-theme') === 'dark', 'Host language and dark theme are applied');
  check((await page.locator('main h2').allTextContents()).includes('Recent files'), 'English pages use the pages namespace');
  await shot('new-dark-1280');
  await open('file', 'README.md'); await shot('file-dark-1280');
  await page.setViewportSize({ width:360, height:800 }); await shot('file-dark-360');
  check(errors.length === 0, `No browser exceptions: ${errors.join(', ')}`);
  return results;
}
