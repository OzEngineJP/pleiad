// Run against an authenticated fake server. Only the page receives the synthetic events.
async page => {
  await page.addInitScript(() => {
    const W = window.WebSocket;
    window.__runningToolSockets = [];
    window.WebSocket = function (...args) { const s = new W(...args); window.__runningToolSockets.push(s); return s; };
    window.WebSocket.prototype = W.prototype;
    Object.assign(window.WebSocket, { CONNECTING: 0, OPEN: 1, CLOSING: 2, CLOSED: 3 });
  });
  await page.reload();
  await page.waitForTimeout(1200);
  const results = await page.evaluate(async () => {
    document.getElementById('onboardingDialog')?.close();
    const ws = window.__runningToolSockets.at(-1);
    const sid = document.querySelector('.row.sel')?.dataset.session ?? localStorage.getItem('agent-host-current');
    if (!sid) throw Error('Open a saved fake conversation before running this test');
    const send = event => ws.onmessage({ data: JSON.stringify({ kind: 'event', event: { sessionId: sid, ...event } }) });
    const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
    const checks = {};
    const q = s => document.querySelector(s);
    const qa = s => [...document.querySelectorAll(s)];
    send({ type: 'activity', state: 'idle' });
    send({ type: 'tool.start', id: 'tail-single', name: 'Bash', input: { command: 'npm test' }, startedAt: Date.now() - 65000 });
    await wait(300);
    const single = q('[data-id="tail-single"]');
    checks.singleAtEnd = single.closest('.mw') === q('#thread > .mw:last-child') && single.closest('.mw').classList.contains('activity');
    checks.singleMark = single.querySelector('.running-tool-mark .run svg path') !== null && single.querySelector('.tc-elapsed').textContent.startsWith('1:');
    checks.onlyOneRow = qa('[data-id="tail-single"]').length === 1;
    const start = single.toolStarted;
    const details = single.querySelector('.tc-details');
    details.open = true;
    single.querySelector('summary').focus();
    send({ type: 'text.delta', text: 'Tools continue while this response is written.' });
    send({ type: 'thinking.start' });
    send({ type: 'thinking.delta', estimatedTokens: 1240 });
    await wait(300);
    checks.textAndThinkingKeepTool = single.closest('.mw') === q('#thread > .mw:last-child') && !q('.m.activity > .txt').checkVisibility();
    checks.noTokens = !q('main').innerText.includes('1240') && !q('main').innerText.includes('トークン）');
    send({ type: 'tool.result', id: 'tail-single', text: 'passed' });
    await wait(300);
    checks.returnedSameRow = q('[data-id="tail-single"]') === single && !single.closest('.activity') && !single.classList.contains('tc-running');
    checks.detailsAndFocus = details.open && document.activeElement === single.querySelector('summary') && single.checkVisibility();
    checks.originalTime = single.toolStarted === start && single.querySelector('.tc-time')?.checkVisibility();
    for (let i = 0; i < 5; i++) send({ type: 'tool.start', id: `tail-many-${i}`, name: i % 2 ? 'Read' : 'Bash', input: i % 2 ? { file_path: `file-${i}.mjs` } : { command: `task-${i}` } });
    await wait(300);
    const order = () => qa('.running-tool-rows > .tc').map(c => c.dataset.id);
    checks.fiveInStartOrder = order().join(',') === [0,1,2,3,4].map(i => `tail-many-${i}`).join(',');
    checks.firstThreeAndMore = qa('.tc-at-end').filter(c => c.checkVisibility()).length === 3 && q('.running-tools-more').textContent.includes('2');
    q('.running-tools-more').click();
    checks.expandFive = qa('.tc-at-end').filter(c => c.checkVisibility()).length === 5;
    send({ type: 'tool.result', id: 'tail-many-3', text: 'done' });
    await wait(300);
    checks.oldUnfinishedRemain = order().join(',') === [0,1,2,4].map(i => `tail-many-${i}`).join(',') && q('[data-id="tail-many-0"]').checkVisibility();
    const waited = q('[data-id="tail-many-1"]');
    send({ type: 'permission', id: 'tail-permission', kind: 'tool', toolName: 'Read', toolUseID: 'tail-many-1', input: { file_path: 'file-1.mjs' }, canAlways: true });
    await wait(300);
    checks.approvalInHistory = !waited.closest('.activity') && waited.classList.contains('tc-waiting') && !waited.querySelector('.run');
    send({ type: 'tool.result', id: 'tail-many-1', text: 'done' });
    for (const i of [0,2,4]) send({ type: 'tool.result', id: `tail-many-${i}`, text: 'done' });
    send({ type: 'activity', state: 'idle' });
    await wait(300);
    checks.finishedNoRunning = !q('.tc-at-end') && !q('.tc-running .run') && !q('.mw.activity');
    send({ type: 'tool.start', id: 'tail-approval-after-text', name: 'Bash', input: { command: 'needs-approval' } });
    send({ type: 'text.delta', text: 'The tool is still pending.' });
    send({ type: 'permission', id: 'tail-approval-after-text-permission', kind: 'tool', toolName: 'Bash', toolUseID: 'tail-approval-after-text', input: { command: 'needs-approval' }, canAlways: true });
    await wait(300);
    const approvalAfterText = q('[data-id="tail-approval-after-text"]');
    checks.approvalAfterText = !approvalAfterText.closest('.activity') && approvalAfterText.classList.contains('tc-waiting') && !approvalAfterText.querySelector('.run') && !approvalAfterText.querySelector('.tc-appr .ln').textContent.includes('実行中');
    send({ type: 'tool.result', id: 'tail-approval-after-text', text: 'done' });
    send({ type: 'activity', state: 'idle' });

    send({ type: 'tool.start', id: 'tail-running-ended', name: 'Bash', input: { command: 'no-result-before-running-ended' } });
    send({ type: 'running', count: 0, turns: [], permissions: [], subagents: [], background: [], tasks: [] });
    await wait(300);
    checks.runningEndedClearsMarks = !q('.tc-at-end') && !q('[data-id="tail-running-ended"] .run') && !q('[data-id="tail-running-ended"]').classList.contains('tc-running');
    return checks;
  });
  const failed = Object.entries(results).filter(([,ok]) => !ok).map(([name]) => name);
  if (failed.length) throw Error(`${failed.join(', ')}: ${JSON.stringify(results)}`);
  return results;
}
