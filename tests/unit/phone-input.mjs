import { createCompositionInput, fieldAt, createPhoneInput } from '../../web/phone-input.mjs';
import { N } from '../lib/dom-stub.mjs';
import { createScreencastInput } from '../../web/screencast-frame.mjs';
export const name = 'phone-input';
export const title = 'スマホの入力: 日本語の変換と確定・タップ内の焦点・パスワード・通常のタップ';
export default async function (t) {
  const sent = [], composition = createCompositionInput(value => sent.push(value));
  composition.start(); composition.update('に'); composition.update('日本'); composition.input('日本', { isComposing: true });
  t.ok('変換中に文字を確定しない', sent.length === 2 && sent.every(value => value.type === 'composition'));
  composition.end('日本', 100); composition.input('日本', { stamp: 101, inputType: 'insertFromComposition' });
  t.ok('確定後の input が来ても一度だけ insertText', sent.filter(value => value.type === 'text').length === 1 && sent.at(-1).text === '日本');
  composition.input('語', { stamp: 200, inputType: 'insertText' });
  t.ok('確定に続けた入力を落とさない', sent.at(-1).text === '語');
  composition.start(); composition.update('未確定'); composition.reset();
  t.ok('タブを替えたときに未確定文字を取り消す', !composition.composing && sent.at(-1).type === 'composition' && sent.at(-1).text === '');
  const fields = [{ id: 1, x: 10, y: 20, width: 100, height: 30, type: 'text' }, { id: 2, x: 10, y: 80, width: 100, height: 30, type: 'password' }];
  t.ok('映像の座標で入力欄を探す', fieldAt(fields, { x: 15, y: 30 }).id === 1 && fieldAt(fields, { x: 0, y: 0 }) === null);
  const oldDoc = globalThis.document, oldWindow = globalThis.window, oldViewport = globalThis.visualViewport, oldHeight = globalThis.innerHeight, oldFocus = N.prototype.focus, oldBlur = N.prototype.blur;
  const doc = { createElement: tag => new N(tag), getElementById: () => null, head: new N('head'), body: new N('body') };
  globalThis.document = doc; globalThis.window = {};
  const viewport = new N('viewport'); viewport.offsetTop = 0; viewport.height = 100;
  globalThis.visualViewport = viewport; globalThis.innerHeight = 640;
  N.prototype.focus = function () { doc.activeElement = this; }; N.prototype.blur = function () { if (doc.activeElement === this) doc.activeElement = null; };
  let phone, video;
  try {
    const surface = new N('div'); surface.getBoundingClientRect = () => ({ left: 0, top: 0, width: 360, height: 640 });
    const pans = [];
    phone = createPhoneInput({ surface, send: value => sent.push(value), getMetadata: () => ({ deviceWidth: 360, deviceHeight: 640 }), onPan: value => pans.push(value) });
    phone.receive({ type: 'fields', fields });
    phone.beforeTap({ x: 15, y: 30 });
    t.ok('タップの呼び出しの中で透明な欄に焦点が入る', doc.activeElement === phone.element);
    const deletion = sent.length; let prevented = false;
    phone.element.dispatchEvent({ type: 'beforeinput', inputType: 'deleteContentBackward', cancelable: true, preventDefault() { prevented = true; } });
    t.ok('端末の文字欄が空でも削除を送り既定の削除を抑える', prevented && sent.length === deletion + 1 && sent.at(-1).key === 'Backspace' && phone.element.value === '\u200b');
    phone.element.dispatchEvent({ type: 'compositionstart' });
    phone.element.dispatchEvent({ type: 'beforeinput', inputType: 'deleteContentBackward', cancelable: true, preventDefault() {} });
    t.ok('日本語の変換中の削除を遠隔の Backspace にしない', sent.length === deletion + 1);
    phone.element.dispatchEvent({ type: 'compositionend', data: '', timeStamp: 300 });
    viewport.height = 60;
    viewport.dispatchEvent({ type: 'resize' }); viewport.dispatchEvent({ type: 'scroll' });
    t.ok('キーボードの位置通知が続いても映像のずらし量を保つ', pans.at(-1) === -14 && pans.at(-2) === -14);
    phone.beforeTap({ x: 0, y: 0 });
    t.ok('普通のページのタップで代わりの入力欄を出さない', phone.fallback.hidden);
    const count = sent.length;
    const allowed = phone.beforeTap({ x: 15, y: 90 });
    t.ok('パスワードを押したときだけ案内し入力は送らない', allowed === false && !phone.sheet.hidden && phone.sheet.textContent.includes('この端末からは使えません') && sent.length === count);
    phone.receive({ type: 'fields', fields: [] });
    t.ok('位置の更新だけでパスワードの入力を送らない', sent.length === count);
    const image = new N('img'), gestures = []; image.naturalWidth = 360; image.naturalHeight = 640; image.getBoundingClientRect = surface.getBoundingClientRect;
    video = createScreencastInput({ surface, img: image, phone: true, getFrame: () => ({ metadata: { deviceWidth: 360, deviceHeight: 640, pageScaleFactor: .5 } }), send: value => gestures.push(value) });
    const pointer = (type, x, stamp, id = 1) => surface.dispatchEvent({ type, target: image, button: 0, pointerId: id, clientX: x, clientY: 30, timeStamp: stamp });
    pointer('pointerdown', 20, 1000); pointer('pointerup', 20, 1010);
    pointer('pointerdown', 200, 1100); pointer('pointerup', 200, 1110);
    await new Promise(resolve => setTimeout(resolve, 300));
    t.ok('離れた位置の連続タップを拡大と誤判定しない', video.zoom === 1 && gestures.length === 2);
    t.ok('縮小されたページでもレイアウト上の座標に変換する', gestures[1].x === 400 && gestures[1].y === 60);
    gestures.length = 0;
    pointer('pointerdown', 30, 2000); pointer('pointerup', 30, 2010);
    pointer('pointerdown', 32, 2100); pointer('pointerup', 32, 2110);
    await new Promise(resolve => setTimeout(resolve, 300));
    t.ok('同じ位置のダブルタップは入力を送らず手元だけ拡大する', video.zoom === 2 && gestures.length === 0);
    video.reset();
    pointer('pointerdown', 60, 3000); pointer('pointerdown', 160, 3010, 2); pointer('pointermove', 260, 3020, 2);
    pointer('pointerup', 60, 3030); pointer('pointerup', 260, 3040, 2);
    t.ok('2 本指の拡大は遠隔のページを操作しない', video.zoom === 2 && gestures.length === 0);
  } finally { video?.destroy(); phone?.destroy(); globalThis.document = oldDoc; globalThis.window = oldWindow; globalThis.visualViewport = oldViewport; globalThis.innerHeight = oldHeight; N.prototype.focus = oldFocus; if (oldBlur) N.prototype.blur = oldBlur; else delete N.prototype.blur; }
}
